async function run() {
  const uri = process.env.MONGODB_URI || 'mongodb://127.0.0.1:27017/pharmacare';
  console.log(`Connecting to ${uri}...`);
  await mongoose.connect(uri);

  const categories = await Category.find();
  const catMap = {};
  categories.forEach((c) => {
    catMap[c.name] = c._id;
  });

  const suppliers = await Supplier.find();
  const defaultSupplier = suppliers[0]?._id;
  const adminUser = await User.findOne({ roleCode: 'ADMIN' });

  let added = 0;
  for (const item of additionalTablets) {
    const existing = await Medicine.findOne({ name: item.name });
    if (existing) {
      console.log(`Already exists: ${item.name}`);
      continue;
    }

    const catId = catMap[item.catName] || categories[0]._id;
    const med = await Medicine.create({
      name: item.name,
      genericName: item.genericName,
      category: catId,
      manufacturer: item.manufacturer,
      dosageForm: item.dosageForm,
      strength: item.strength,
      schedule: item.schedule,
      prescriptionRequired: item.prescriptionRequired,
      barcode: item.barcode,
      hsnCode: item.hsnCode,
      gstRate: item.gstRate,
      reorderLevel: item.reorderLevel,
      rackLocation: item.rackLocation,
      totalStock: item.qty,
    });

    const mfgDate = new Date();
    mfgDate.setDate(mfgDate.getDate() + item.mfgOffsetDays);

    const expDate = new Date();
    expDate.setDate(expDate.getDate() + item.expOffsetDays);

    const batch = await MedicineBatch.create({
      medicine: med._id,
      batchNumber: item.batchNumber,
      manufacturingDate: mfgDate,
      expiryDate: expDate,
      purchasePrice: item.purchasePrice,
      mrp: item.mrp,
      sellingPrice: item.sellingPrice,
      initialQuantity: item.qty + 25,
      quantity: item.qty,
      supplier: defaultSupplier,
      rackLocation: item.rackLocation,
      status: 'ACTIVE',
    });

    await InventoryMovement.create({
      medicine: med._id,
      batch: batch._id,
      type: 'PURCHASE_RECEIPT',
      quantity: item.qty,
      previousStock: 0,
      newStock: item.qty,
      reason: 'Tablet catalog replenishment',
      performedBy: adminUser ? adminUser._id : null,
    });

    added++;
    console.log(`Added tablet: ${item.name}`);
  }

  console.log(`Successfully added ${added} new tablet formulations!`);
  await mongoose.disconnect();
}

run().catch((e) => {
  console.error(e);
  process.exit(1);
});
